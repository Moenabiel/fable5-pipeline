"""LoRA fine-tuning script for the Fable5 pipeline.

Trains a LoRA adapter on synthetic instruction data generated by a teacher model.
Designed to run on free Colab T4 GPU with 4-bit quantized base model.

Usage:
    python src/train_lora.py \
        --model-id mistralai/Mistral-7B-Instruct-v0.3 \
        --dataset data/instructions.jsonl \
        --epochs 2 \
        --lora-r 8 \
        --lora-alpha 16 \
        --batch-size 8 \
        --output-dir models/lora-adapter
"""

import argparse
import json
import os
from typing import Optional


def load_dataset(path: str) -> list[dict]:
    """Load instruction dataset from JSONL file.

    Expected format per line:
    {"instruction": "...", "input": "...", "output": "..."}
    or
    {"messages": [{"role": "system", "content": "..."}, {"role": "user", "content": "..."}, {"role": "assistant", "content": "..."}]}
    """
    data = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            item = json.loads(line)
            if "messages" in item:
                data.append(item)
            elif "instruction" in item:
                messages = []
                if item.get("input"):
                    messages.append({"role": "system", "content": "You are a helpful assistant."})
                    messages.append({"role": "user", "content": f"{item['instruction']}\n\n{item['input']}"})
                else:
                    messages.append({"role": "system", "content": "You are a helpful assistant."})
                    messages.append({"role": "user", "content": item["instruction"]})
                messages.append({"role": "assistant", "content": item["output"]})
                data.append({"messages": messages})
    return data


def train(
    model_id: str,
    dataset_path: str,
    output_dir: str = "models/lora-adapter",
    epochs: int = 2,
    lora_r: int = 8,
    lora_alpha: int = 16,
    lora_dropout: float = 0.05,
    batch_size: int = 8,
    learning_rate: float = 2e-4,
    max_seq_length: int = 1024,
    warmup_steps: int = 10,
):
    """Train a LoRA adapter on instruction data."""
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig, TrainingArguments
    from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
    from datasets import Dataset

    print(f"Loading model: {model_id}")
    bnb_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_compute_dtype=torch.float16,
        bnb_4bit_use_double_quant=True,
    )
    tokenizer = AutoTokenizer.from_pretrained(model_id)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        model_id,
        quantization_config=bnb_config,
        device_map="auto",
    )
    model = prepare_model_for_kbit_training(model)

    lora_config = LoraConfig(
        r=lora_r,
        lora_alpha=lora_alpha,
        lora_dropout=lora_dropout,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    )
    model = get_peft_model(model, lora_config)
    model.print_trainable_parameters()

    print(f"Loading dataset: {dataset_path}")
    raw_data = load_dataset(dataset_path)
    print(f"Loaded {len(raw_data)} examples")

    def tokenize_fn(examples):
        texts = []
        for messages in examples["messages"]:
            text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=False)
            texts.append(text)
        tokenized = tokenizer(
            texts,
            truncation=True,
            max_length=max_seq_length,
            padding="max_length",
        )
        tokenized["labels"] = tokenized["input_ids"].copy()
        return tokenized

    dataset = Dataset.from_dict({"messages": [d["messages"] for d in raw_data]})
    tokenized_dataset = dataset.map(tokenize_fn, batched=True, remove_columns=["messages"])

    os.makedirs(output_dir, exist_ok=True)
    training_args = TrainingArguments(
        output_dir=output_dir,
        num_train_epochs=epochs,
        per_device_train_batch_size=batch_size,
        learning_rate=learning_rate,
        warmup_steps=warmup_steps,
        logging_steps=5,
        save_strategy="epoch",
        fp16=True,
        report_to="none",
    )

    from transformers import Trainer
    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=tokenized_dataset,
    )

    print("Starting training...")
    trainer.train()

    model.save_pretrained(output_dir)
    tokenizer.save_pretrained(output_dir)
    print(f"LoRA adapter saved to: {output_dir}")


def generate_synthetic_data(
    teacher_model_id: str,
    prompts: list[str],
    output_path: str,
    system_prompt: str = "You are a helpful assistant that shows step-by-step reasoning.",
):
    """Generate synthetic training data using a teacher model.

    This uses the free HuggingFace inference API or local model to generate
    chain-of-thought responses that students can learn from.
    """
    from transformers import pipeline

    pipe = pipeline("text-generation", model=teacher_model_id, device_map="auto")
    data = []
    for prompt in prompts:
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ]
        output = pipe(messages, max_new_tokens=512, temperature=0.7)
        response = output[0]["generated_text"][-1]["content"]
        data.append({
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt},
                {"role": "assistant", "content": response},
            ]
        })

    with open(output_path, "w", encoding="utf-8") as f:
        for item in data:
            f.write(json.dumps(item) + "\n")
    print(f"Generated {len(data)} synthetic examples to {output_path}")


def main():
    parser = argparse.ArgumentParser(description="LoRA Fine-Tuning for Fable5 Pipeline")
    parser.add_argument("--model-id", default="mistralai/Mistral-7B-Instruct-v0.3")
    parser.add_argument("--dataset", required=True, help="Path to JSONL instruction dataset")
    parser.add_argument("--output-dir", default="models/lora-adapter")
    parser.add_argument("--epochs", type=int, default=2)
    parser.add_argument("--lora-r", type=int, default=8)
    parser.add_argument("--lora-alpha", type=int, default=16)
    parser.add_argument("--lora-dropout", type=float, default=0.05)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--learning-rate", type=float, default=2e-4)
    parser.add_argument("--max-seq-length", type=int, default=1024)
    parser.add_argument("--warmup-steps", type=int, default=10)
    parser.add_argument("--generate-synthetic", action="store_true", help="Generate synthetic data first")
    parser.add_argument("--synthetic-prompts", help="JSONL file with prompts for synthetic generation")
    args = parser.parse_args()

    if args.generate_synthetic and args.synthetic_prompts:
        prompts = []
        with open(args.synthetic_prompts) as f:
            for line in f:
                item = json.loads(line.strip())
                prompts.append(item.get("prompt", item.get("instruction", "")))
        synthetic_path = "data/synthetic_instructions.jsonl"
        generate_synthetic_data(args.model_id, prompts, synthetic_path)
        args.dataset = synthetic_path

    train(
        model_id=args.model_id,
        dataset_path=args.dataset,
        output_dir=args.output_dir,
        epochs=args.epochs,
        lora_r=args.lora_r,
        lora_alpha=args.lora_alpha,
        lora_dropout=args.lora_dropout,
        batch_size=args.batch_size,
        learning_rate=args.learning_rate,
        max_seq_length=args.max_seq_length,
        warmup_steps=args.warmup_steps,
    )


if __name__ == "__main__":
    main()
